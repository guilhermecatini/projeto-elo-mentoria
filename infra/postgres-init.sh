#!/usr/bin/env bash
set -Eeuo pipefail
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$DB_APP_PASSWORD" <<'SQL'
CREATE ROLE elo_app LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEDB NOCREATEROLE;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO elo_app;
GRANT CONNECT ON DATABASE elo TO elo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE elo_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO elo_app;
ALTER DEFAULT PRIVILEGES FOR ROLE elo_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO elo_app;
SQL
